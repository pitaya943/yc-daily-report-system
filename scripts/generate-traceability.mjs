#!/usr/bin/env node
/**
 * Regenerate docs/design/traceability.md from test file scans.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const roots = [
  'apps/api',
  'packages/validation',
  'packages/allocation',
  'packages/payroll',
  'packages/bank-crypto',
  'e2e',
];

const byId = new Map();

function add(id, file, label) {
  if (!byId.has(id)) byId.set(id, []);
  byId.get(id).push({ file, label });
}

function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    const st = statSync(p);
    if (st.isDirectory() && name !== 'node_modules' && name !== 'dist') {
      walk(p);
    } else if (/\.(spec|test)\.(ts|tsx)$/.test(name)) {
      const text = readFileSync(p, 'utf8');
      const lines = text.split('\n');
      let currentDescribe = '';
      for (const line of lines) {
        const d = line.match(/describe\(['`]([^'"]+)['`]/);
        if (d) currentDescribe = d[1];
        const t = line.match(/(?:it|test)\(['`]([^'"]+)['`]/);
        const ids = [...new Set([...(currentDescribe.matchAll(/B-\d{3}/g)).map((m) => m[0]), ...(line.matchAll(/BDD-\d{3}/g)).map((m) => m[0]), ...(line.matchAll(/B-\d{3}/g)).map((m) => m[0])])];
        for (const id of ids) {
          const label = t ? `${currentDescribe || name} → ${t[1]}` : currentDescribe || name;
          add(id, p, label);
        }
      }
      for (const m of name.matchAll(/B-\d{3}/g)) {
        add(m[0], p, name);
      }
      for (const m of text.matchAll(/describe\(['`]([^'"]*B-\d{3}[^'"]*)['`]/g)) {
        add(m[0].match(/B-\d{3}/)[0], p, m[1]);
      }
      for (const m of text.matchAll(/describe\(['`]([^'"]*BDD-\d{3}[^'"]*)['`]/g)) {
        add(m[0].match(/BDD-\d{3}/)[0], p, m[1]);
      }
    }
  }
}

for (const root of roots) walk(root);

let md = `# Traceability matrix

Maps every active **B-001–B-098** and **BDD-001–BDD-011** rule to automated tests (file + describe/test name). Generated by \`node scripts/generate-traceability.mjs\`.

CI enforces B-001–B-050 via \`scripts/check-b-rule-coverage.mjs\`; B-051–B-098 are report-only until S6b.

## B-rules

| ID | Test file(s) | Test name(s) |
|----|--------------|--------------|
`;

for (let n = 1; n <= 98; n++) {
  const id = `B-${String(n).padStart(3, '0')}`;
  const rows = byId.get(id) ?? [];
  if (rows.length === 0) {
    md += `| ${id} | — | *(no test yet — S6b)* |\n`;
    continue;
  }
  const files = [...new Set(rows.map((r) => r.file))].join('; ');
  const names = [...new Set(rows.map((r) => r.label))].slice(0, 4).join('; ');
  md += `| ${id} | \`${files}\` | ${names}${rows.length > 4 ? ' …' : ''} |\n`;
}

md += `\n## BDD scenarios\n\n| ID | Test file(s) | Test name(s) |\n|----|--------------|--------------|\n`;

for (let n = 1; n <= 11; n++) {
  const id = `BDD-${String(n).padStart(3, '0')}`;
  const rows = byId.get(id) ?? [];
  if (rows.length === 0) {
    md += `| ${id} | — | *(planned)* |\n`;
    continue;
  }
  const files = [...new Set(rows.map((r) => r.file))].join('; ');
  const names = [...new Set(rows.map((r) => r.label))].join('; ');
  md += `| ${id} | \`${files}\` | ${names} |\n`;
}

writeFileSync('docs/design/traceability.md', md);
console.log('Wrote docs/design/traceability.md');
